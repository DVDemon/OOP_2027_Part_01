// Пример 01: структура программы и точка входа main.
//
// Демонстрирует:
//   * минимальную структуру программы на C++;
//   * две формы main: без аргументов и с argc/argv;
//   * чтение аргументов командной строки;
//   * смысл кода возврата.

#include <iostream>

// Точка входа в программу. Форма с аргументами командной строки:
//   argc — количество аргументов (всегда >= 1, argv[0] — имя программы);
//   argv — массив C-строк, argv[argc] == nullptr.
int main(int argc, char* argv[]) {
    std::cout << "Hello, C++20!\n";

    std::cout << "Передано аргументов (включая имя программы): " << argc << '\n';
    for (int i = 0; i < argc; ++i) {
        std::cout << "  argv[" << i << "] = " << argv[i] << '\n';
    }

    // return 0; означает успешное завершение.
    // Именно для main допустимо опустить return — компилятор подставит 0.
    // Для любой другой не-void функции отсутствие return — UB.
    return 0;
}
