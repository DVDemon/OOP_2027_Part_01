// Пример 06: типичные ошибки памяти и КАК их избегать.
// В этом файле — только ПРАВИЛЬНЫЙ код. Сами ошибки (UB) разобраны в README
// как сниппеты; в коде мы показываем безопасные варианты.
#include <iostream>

// Плохо (см. README): возврат адреса локальной переменной -> dangling pointer.
// Хорошо: возвращаем значение (копию) — у вызывающего своя переменная.
int make_value() {
    int local = 42;
    return local;  // возвращаем по значению, не &local
}

// Хорошо: единственный владелец освобождает память ровно один раз.
void process_safely() {
    int* p = new int(42);
    // ... работа с *p ...
    std::cout << "process_safely: *p = " << *p << '\n';
    delete p;
    p = nullptr;  // защита от повторного использования/double free
}

int main() {
    // 1. Вместо dangling pointer — возврат по значению.
    int v = make_value();
    std::cout << "make_value() = " << v << '\n';

    // 2. Вместо memory leak — каждый new имеет парный delete на всех путях.
    process_safely();

    // 3. Вместо use-after-free — обнуляем указатель после delete.
    int* q = new int(7);
    std::cout << "*q = " << *q << '\n';
    delete q;
    q = nullptr;  // теперь случайный *q легко поймать проверкой на nullptr
    if (q == nullptr) {
        std::cout << "q безопасно обнулён после delete\n";
    }

    // 4. Вместо double free — ровно один владелец и одно освобождение.
    //    (Совместное владение решается умными указателями — позже в курсе.)
    std::cout << "Ошибки разобраны в README; здесь только корректный код.\n";
    return 0;
}
