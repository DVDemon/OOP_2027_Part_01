// Пример 02: оператор взятия адреса (&), разыменование (*), арифметика указателей.
#include <cstddef>
#include <iostream>

int main() {
    int x = 42;
    int* ptr = &x;  // ptr хранит адрес x

    std::cout << "--- Адрес и разыменование ---\n";
    std::cout << "Значение x:        " << x << '\n';                          // 42
    std::cout << "Адрес x:           " << static_cast<void*>(&x) << '\n';     // 0x...
    std::cout << "Значение ptr:      " << static_cast<void*>(ptr) << '\n';    // тот же адрес
    std::cout << "Разыменование ptr: " << *ptr << '\n';                       // 42

    *ptr = 100;  // изменяем значение по адресу
    std::cout << "x после *ptr=100:  " << x << "\n\n";                        // 100

    // --- Арифметика указателей ---
    int arr[] = {10, 20, 30, 40, 50};
    int* p = arr;  // указатель на первый элемент

    std::cout << "--- Арифметика указателей ---\n";
    std::cout << "*p       = " << *p << '\n';        // 10
    std::cout << "*(p + 1) = " << *(p + 1) << '\n';  // 20
    std::cout << "*(p + 2) = " << *(p + 2) << '\n';  // 30

    p += 3;  // сдвиг на 3 элемента (3 * sizeof(int) байт), а не на 3 байта
    std::cout << "после p += 3, *p = " << *p << '\n';  // 40

    // Разность указателей — число элементов между ними.
    int* begin = arr;
    int* end = arr + 5;  // «один за концом» — допустимо для арифметики
    std::ptrdiff_t diff = end - begin;
    std::cout << "end - begin = " << diff << " элементов\n";

    return 0;
}
