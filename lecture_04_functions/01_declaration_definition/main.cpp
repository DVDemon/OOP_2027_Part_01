// Пример 01: объявление vs определение функции. Прототипы.
#include <iostream>

#include "math_utils.h"  // здесь компилятор видит только ОБЪЯВЛЕНИЯ

// Локальный прототип: можно объявить функцию прямо перед использованием,
// а определить ниже. Компилятору достаточно объявления, чтобы проверить вызов.
int square(int x);

int main() {
    // Вызовы add/multiply компилируются по объявлениям из math_utils.h.
    // Линковщик свяжет их с определениями из math_utils.cpp.
    std::cout << "add(2, 3)      = " << mu::add(2, 3) << '\n';
    std::cout << "multiply(4, 5) = " << mu::multiply(4, 5) << '\n';

    // square объявлена выше, а определена ниже — это работает благодаря прототипу.
    std::cout << "square(6)      = " << square(6) << '\n';

    return 0;
}

// Определение square: одно на программу.
int square(int x) {
    return x * x;
}
