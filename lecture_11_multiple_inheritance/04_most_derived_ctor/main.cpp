// Пример 04: ответственность наиболее производного класса (most-derived).
//
// Демонстрирует:
//   * при виртуальном наследовании конструктор виртуальной базы вызывает
//     ТОЛЬКО наиболее производный класс;
//   * вызовы A(...) внутри промежуточных B и C игнорируются, когда они не
//     являются most-derived;
//   * если объект B создаётся напрямую — most-derived уже сам B.

#include <iostream>

class A {
public:
    explicit A(int x) { std::cout << "A(" << x << ")\n"; }
    // Нет конструктора по умолчанию специально: чтобы most-derived класс
    // был ОБЯЗАН вызвать A(int) явно (иначе ошибка компиляции).
};

class B : virtual public A {
public:
    // A(1) сработает, только если B сам — most-derived объект.
    B() : A(1) { std::cout << "B()\n"; }
};

class C : virtual public A {
public:
    // A(2) сработает, только если C сам — most-derived объект.
    C() : A(2) { std::cout << "C()\n"; }
};

class D : public B, public C {
public:
    // D — most-derived: именно он вызывает конструктор виртуальной базы A.
    // Вызовы A(1) из B и A(2) из C при создании D игнорируются.
    D() : A(999), B(), C() { std::cout << "D()\n"; }
};

int main() {
    std::cout << "=== Создаём D ===\n";
    D d;
    // Ожидаемо:
    //   A(999)  <- вызван из D, НЕ из B или C
    //   B()
    //   C()
    //   D()

    std::cout << "=== Создаём B напрямую ===\n";
    B b;
    // Здесь B сам является most-derived, поэтому работает его A(1):
    //   A(1)
    //   B()

    (void)d;
    (void)b;
    return 0;
}
