// Пример 04: приоритет, ассоциативность, инкремент/декремент.
#include <iostream>
#include <vector>

int main() {
    std::cout << "=== Приоритет операторов ===\n";
    // * выше +, поэтому скобки не нужны, но они улучшают читаемость.
    std::cout << "2 + 3 * 4       = " << (2 + 3 * 4) << "  (== 14, не 20)\n";
    std::cout << "(2 + 3) * 4     = " << ((2 + 3) * 4) << "\n";

    // << имеет более высокий приоритет, чем сравнения и +,
    // поэтому сложные выражения в cout надо брать в скобки.
    int a = 1, b = 2;
    std::cout << "a + b           = " << (a + b) << '\n';
    // ПЛОХО: std::cout << a + b == 3;  // разбор: (cout << a + b) == 3 — ошибка типов

    std::cout << "\n=== Ассоциативность ===\n";
    // Присваивание правоассоциативно: x = y = 5 -> x = (y = 5).
    int x = 0, y = 0;
    x = y = 5;
    std::cout << "после x = y = 5: x=" << x << " y=" << y << '\n';
    // Вычитание левоассоциативно: 10 - 3 - 2 -> (10 - 3) - 2 == 5.
    std::cout << "10 - 3 - 2      = " << (10 - 3 - 2) << '\n';

    std::cout << "\n=== Префиксный и постфиксный инкремент ===\n";
    int n = 5;
    int pre = ++n;   // сначала n=6, затем вернуть -> pre=6, n=6
    int post = n++;  // сначала вернуть 6, затем n=7 -> post=6, n=7
    std::cout << "n=" << n << " pre=" << pre << " post=" << post << '\n';


    std::cout << "\n=== Неопределённое поведение: i = i++ ===\n";
    // ПЛОХО: int i = 0; i = i++ + ++i;  // UB до C++17 / неочевидно — НЕ ПИШИТЕ так.
    // ХОРОШО: разбивайте на отдельные инструкции с явным порядком.
    int i = 0;
    ++i;            // i = 1
    int result = i; // result = 1
    ++i;            // i = 2
    std::cout << "i=" << i << " result=" << result << " (всё явно и предсказуемо)\n";

    return 0;
}
