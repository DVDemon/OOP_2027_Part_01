// Пример 10: break, continue и оператор «запятая».
#include <iostream>

int main() {
    std::cout << "=== break: выход из цикла ===\n";
    for (int i = 0; i < 100; ++i) {
        if (i * i > 50) {
            std::cout << "первое i, где i*i > 50: " << i << '\n';
            break;  // покидаем цикл досрочно
        }
    }

    std::cout << "\n=== continue: пропуск итерации ===\n";
    for (int i = 0; i < 20; ++i) {
        if (i % 3 == 0) {
            continue;  // пропускаем кратные 3
        }
        std::cout << i << ' ';
    }
    std::cout << '\n';

    std::cout << "\n=== Выход из вложенных циклов через флаг ===\n";
    // ПЛОХО: break выходит только из ВНУТРЕННЕГО цикла.
    //        goto работает, но обычно его избегают.
    // ХОРОШО: флаг (или вынести в функцию и вернуть значение).
    bool found = false;
    int fi = -1, fj = -1;
    for (int i = 0; i < 5 && !found; ++i) {
        for (int j = 0; j < 5; ++j) {
            if (i * j == 6) {
                fi = i;
                fj = j;
                found = true;
                break;  // выходим из внутреннего цикла
            }
        }
    }
    std::cout << "i*j==6 при i=" << fi << ", j=" << fj << '\n';

    std::cout << "\n=== Оператор «запятая» ===\n";
    // Вычисляет оба операнда слева направо, результат — правый.
    int a = (1, 2, 3);  // a == 3
    std::cout << "(1, 2, 3) = " << a << '\n';

    // Типичное (и уместное) применение — в секции for:
    std::cout << "for с (++i, --j): ";
    for (int i = 0, j = 6; i < j; ++i, --j) {
        std::cout << '(' << i << ',' << j << ") ";
    }
    std::cout << '\n';

    // ПЛОХО: запятая в произвольных выражениях запутывает.
    //   int x = (compute_a(), compute_b());  // x == compute_b(), a отброшено
    // ХОРОШО: отдельные инструкции читаются однозначно.

    return 0;
}
